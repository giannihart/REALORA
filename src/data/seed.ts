function photosFor(heroId: string, count = 6): string[] {
  const interiors = GALLERY_IDS.filter((id) => id !== heroId);
  const start = heroId.length % Math.max(1, interiors.length);
  const rotated = [...interiors.slice(start), ...interiors.slice(0, start)];
  return [heroId, ...rotated.slice(0, Math.max(0, count - 1))].map((id) => u(id));
}

